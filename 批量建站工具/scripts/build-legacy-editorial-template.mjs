/** Extract the supplied editorial renderer without starting its old workbench.
 * Source snapshots stay byte-identical. Page/config/random functions run in a
 * private scope; upload, archive and advertising runtimes belong to the host.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { parse } from '@babel/parser';
import { parseHTML } from 'linkedom';

const root = new URL('../', import.meta.url);
const sources = {}, hashes = {};
for (const name of ['index.html', 'js/data.js', 'js/generator.js', 'js/app.js']) {
    const bytes = await readFile(new URL('legacy-editorial-source/' + name, root));
    sources[name] = bytes.toString('utf8');
    hashes[name] = createHash('sha256').update(bytes).digest('hex');
}
const appTree = parse(sources['js/app.js']);
const appBody = appTree.program.body.find(n => n.type === 'ExpressionStatement').expression.callee.body.body;
const generatorBody = parse(sources['js/generator.js']).program.body
    .find(n => n.type === 'VariableDeclaration' && n.declarations[0].id.name === 'Generator').declarations[0].init.callee.body.body;
function select(source, body, names) {
    return names.map(name => {
        const node = body.find(n => n.type === 'FunctionDeclaration' && n.id.name === name);
        if (!node) throw new Error('Missing legacy editorial function: ' + name);
        return source.slice(node.start, node.end);
    }).join('\n\n');
}
// In this version defaults were an object in the theme-card click handler.
// Extract that exact object instead of maintaining a hand-written approximation.
let defaultsNode;
function visit(node) {
    if (!node || typeof node !== 'object') return;
    if (node.type === 'AssignmentExpression' && node.left.type === 'MemberExpression' &&
        node.left.object.name === 'appState' && node.left.property.name === 'config' && node.right.type === 'ObjectExpression') defaultsNode = node.right;
    for (const value of Object.values(node)) {
        if (Array.isArray(value)) value.forEach(visit);
        else if (value && typeof value === 'object') visit(value);
    }
}
visit(appTree.program);
if (!defaultsNode) throw new Error('Legacy editorial defaults not found');
const pages = ['generateCSS', 'generateIndexHtml', 'generateScriptJs', 'generateDetailHtml', 'generateContactHtml',
    'generateAboutHtml', 'generatePrivacyHtml', 'generateTermsHtml', 'generatePreviewHtml'];
const helpers = ['simpleMarkdownToHtml', 'generateKeywords', 'getItemId', 'getImageSrc', 'generateNavbar', 'generateFooter',
    'generateContactBody', 'generateAboutBody', 'generatePrivacyBody', 'generateTermsBody'];
const generator = select(sources['js/generator.js'], generatorBody, [...helpers, ...pages, 'buildConfig'])
    .replace('function buildConfig(', 'function buildOriginalConfig(');
const { document } = parseHTML(sources['index.html']);
const controls = Object.fromEntries(Array.from(document.querySelectorAll('select[id]')).map(e => [e.id,
    Array.from(e.querySelectorAll('option')).map(o => ({ value: o.value, label: o.textContent }))]));
const output = `// Generated by build-legacy-editorial-template.mjs. Do not edit source snapshots.
const LegacyEditorialTemplateSource = (function() {
${sources['js/data.js']}
let _googleFontLink = '', activeConfig = null, AD_TEMPLATES = {};
const appState = { config: {} };
${select(sources['js/app.js'], appBody, ['randomPick', 'generateRandomConfig'])}
${generator}
function buildConfig(state) { return activeConfig || buildOriginalConfig(state); }
const renderers = { ${pages.join(', ')} };
return {
    themes: THEMES, presets: STYLE_PRESETS,
    controls: ${JSON.stringify(controls)}, hashes: ${JSON.stringify(hashes)},
    defaults(themeId) {
        const theme = THEMES[themeId];
        if (!theme) throw new Error('Unknown legacy editorial theme: ' + themeId);
        return ${sources['js/app.js'].slice(defaultsNode.start, defaultsNode.end)};
    },
    randomize(config) { appState.config = config; generateRandomConfig(); },
    buildConfig: buildOriginalConfig,
    render(name, args, config, containers) {
        const previous = activeConfig, previousContainers = AD_TEMPLATES;
        activeConfig = config; AD_TEMPLATES = containers;
        try { return renderers[name](...args); }
        finally { activeConfig = previous; AD_TEMPLATES = previousContainers; }
    }
};
})();
`;
const target = new URL('js/legacy-editorial-template-source.js', root);
if (await readFile(target, 'utf8').catch(() => '') !== output) await writeFile(target, output);
console.log('Legacy editorial source verified: ' + hashes['js/generator.js'].slice(0, 16));
