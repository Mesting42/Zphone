/** Build a private renderer from the untouched, user-supplied legacy source.
 * Only presentation/configuration functions are selected. The old application,
 * ZIP writer and advertising runtime are never installed in the new workbench.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { parse } from '@babel/parser';
import { parseHTML } from 'linkedom';

const root = new URL('../', import.meta.url);
const sourceRoot = new URL('game-builder/legacy-source/', root);
const sources = {};
const hashes = {};
for (const name of ['index.html', 'js/data.js', 'js/generator.js', 'js/app.js']) {
  const bytes = await readFile(new URL(name, sourceRoot));
  sources[name] = bytes.toString('utf8');
  hashes[name] = createHash('sha256').update(bytes).digest('hex');
}

function outerBody(source, variable) {
  const body = parse(source).program.body;
  return variable
    ? body.find(node => node.type === 'VariableDeclaration' && node.declarations[0].id.name === variable).declarations[0].init.callee.body.body
    : body.find(node => node.type === 'ExpressionStatement').expression.callee.body.body;
}
function selectFunctions(source, body, names) {
  return names.map(name => {
    const node = body.find(node => node.type === 'FunctionDeclaration' && node.id.name === name);
    if (!node) throw new Error('Legacy source is missing function: ' + name);
    return source.slice(node.start, node.end);
  }).join('\n\n');
}

const pageNames = ['generateCSS', 'generateIndexHtml', 'generateScriptJs', 'generateDetailHtml',
  'generateContactHtml', 'generateAboutHtml', 'generatePrivacyHtml', 'generateTermsHtml', 'generatePreviewHtml'];
const generatorNames = ['simpleMarkdownToHtml', 'generateKeywords', 'getItemId', 'getImageSrc', 'generateNavbar', 'generateFooter',
  'generateContactBody', 'generateAboutBody', 'generatePrivacyBody', 'generateTermsBody', ...pageNames, 'buildConfig'];
const generator = selectFunctions(sources['js/generator.js'], outerBody(sources['js/generator.js'], 'Generator'), generatorNames)
  .replace('function buildConfig(', 'function buildOriginalConfig(');
const app = selectFunctions(sources['js/app.js'], outerBody(sources['js/app.js']), ['initDefaultConfig', 'randomPick', 'generateRandomConfig']);
const { document } = parseHTML(sources['index.html']);
const controls = Object.fromEntries(Array.from(document.querySelectorAll('select[id]')).map(select => [select.id,
  Array.from(select.querySelectorAll('option')).map(option => ({ value: option.value, label: option.textContent }))]));

const output = `// Generated by scripts/build-legacy-game-template.mjs. Preserve legacy-source/ unchanged.
const LegacyGameTemplateSource = (function() {
${sources['js/data.js']}
let _googleFontLink = '';
let AD_TEMPLATES = {};
let activeConfig = null;
const appState = { config: {} };
${app}
${generator}
// The host supplies ad placements/containers after its existing validation.
// This is the only seam between legacy page templates and the current app.
function buildConfig(state) { return activeConfig || buildOriginalConfig(state); }
const renderers = { ${pageNames.join(', ')} };
return {
  theme: THEMES.game,
  presets: STYLE_PRESETS,
  controls: ${JSON.stringify(controls)},
  hashes: ${JSON.stringify(hashes)},
  defaults() { initDefaultConfig(); return JSON.parse(JSON.stringify(appState.config)); },
  randomize(config) { appState.config = config; generateRandomConfig(); },
  buildConfig: buildOriginalConfig,
  render(name, args, config, containers) {
    const previous = activeConfig;
    const previousContainers = AD_TEMPLATES;
    activeConfig = config;
    AD_TEMPLATES = containers;
    try { return renderers[name](...args); }
    finally { activeConfig = previous; AD_TEMPLATES = previousContainers; }
  }
};
})();
`;
const outputPath = new URL('game-builder/js/legacy-template-source.js', root);
if (await readFile(outputPath, 'utf8').catch(() => '') !== output) await writeFile(outputPath, output);
console.log('Legacy game presentation copied from verified source: ' + hashes['js/generator.js'].slice(0, 16));
