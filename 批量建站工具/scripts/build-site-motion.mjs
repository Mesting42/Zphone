// Bundle local runtime/CSS/icon sources into a classic global for both builders.
import { build } from 'esbuild';
import { readFile,writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
// Validate hashes and pack committed artwork offline before bundling.
await import('./vendor-motion-icons.mjs');
const outfile = new URL('../js/site-motion.js',import.meta.url);
const result = await build({entryPoints:[fileURLToPath(new URL('../motion/registry.js',import.meta.url))],bundle:true,format:'iife',platform:'browser',target:'es2020',loader:{'.css':'text','.txt':'text'},write:false,banner:{js:'/* Generated from motion/. Run npm run motion:build; do not edit this file. */'}});
const source=result.outputFiles[0].text;
let previous='';try{previous=await readFile(outfile,'utf8');}catch{}
if(previous!==source)await writeFile(outfile,source);
console.log('Shared site motion runtime generated.');
