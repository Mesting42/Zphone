import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, transform } from 'esbuild';
import vm from 'node:vm';
// Build the isolated legacy renderer from immutable source snapshots first.
import './build-legacy-game-template.mjs';
import './build-legacy-editorial-template.mjs';
import { discoverTemplatePackages } from '../template-system/package-files.mjs';

const appRoot = fileURLToPath(new URL('../', import.meta.url));
const packages = await discoverTemplatePackages(resolve(appRoot, 'templates'));
const imports = ['import { createTemplateRegistry } from "./template-system/registry.js";'];
const registrations = [];
for (const [index, item] of packages.entries()) {
  const folder = './' + relative(appRoot, item.folder).replaceAll('\\', '/');
  imports.push(`import manifest${index} from ${JSON.stringify(folder + '/template.json')};`);
  for (const page of ['home', 'detail', 'all']) imports.push(`import * as ${page}${index} from ${JSON.stringify(folder + '/' + page + '.js')};`);
  imports.push(`import thumbnail${index} from ${JSON.stringify(folder + '/thumbnail.svg')};`);
  if (item.manifest.schemaVersion === 2) {
    for (const part of ['shell','navigation','footer']) imports.push(`import * as ${part}${index} from ${JSON.stringify(folder + '/' + part + '.js')};`);
  }
  registrations.push(`registry.register({ manifest: manifest${index}, pages: { home: home${index}, detail: detail${index}, all: all${index} }, thumbnail: thumbnail${index}${item.manifest.schemaVersion === 2 ? `, presentation: {shell: shell${index}, navigation: navigation${index}, footer: footer${index}}` : ''} });`);
}
// The classic entry runs after data.js and before Generator/app.js. No async
// fetch or new script ordering requirement is introduced into exported sites.
const source = `${imports.join('\n')}
const registry = createTemplateRegistry();
${registrations.join('\n')}
registry.install({ root: globalThis, catalog: DOMAIN_CATALOG, presets: TEMPLATE_PRESETS, palettes: STYLE_PRESETS, fontPresets: FONT_PRESETS });
globalThis.TemplateRegistry = registry;
`;
const result = await build({
  stdin: { contents: source, resolveDir: appRoot, sourcefile: 'template-packages-entry.js' },
  bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2020',
  loader: { '.svg': 'text' }, legalComments: 'none',
  banner: { js: '// Generated by npm run templates:build. Edit templates/ or template-system/, not this file.' }
});
const output = result.outputFiles[0].text;
// Check the same classic-runtime ordering before publishing generated bytes.
// This also catches unknown domains/layouts, preset collisions and invalid page
// declarations before a bad package can interrupt the browser application.
const context = { console };
for (const filename of ['template-catalog.js', 'template-layouts.js', 'data.js']) {
  vm.runInNewContext(await readFile(resolve(appRoot, 'js', filename), 'utf8'), context, { timeout: 10000 });
}
vm.runInNewContext(output, context, { timeout: 10000 });
// JavaScript bundling cannot detect a typo inside a CSS string. Parse every v2
// sheet before replacing the runtime; a broken package leaves the old build intact.
for (const manifest of context.TemplateRegistry.list()) {
  if (manifest.schemaVersion === 2) await transform(context.TemplateRegistry.get(manifest.id).presentationCSS, { loader: 'css', logLevel: 'silent' });
}
const outputPath = resolve(appRoot, 'js/template-packages.js');
const previous = await readFile(outputPath, 'utf8').catch(() => '');
if (output !== previous) await writeFile(outputPath, output, 'utf8');

// Vite treats ?v= URLs as immutable. Publish each validated runtime under a
// content-derived URL only after writing the bundle, so an open browser cannot
// reuse a previous registry with a newer generator. The module entry and tool
// stylesheet follow the same rule; repeated builds keep identical URLs.
const indexPath = resolve(appRoot, 'index.html');
const previousIndex = await readFile(indexPath, 'utf8');
let versionedIndex = previousIndex;
for (const asset of ['js/template-packages.js', 'js/navbar-layout.js', 'js/generator.js', 'js/legacy-editorial-template-source.js', 'js/editorial-template-versions.js', 'js/finished-site-ads.js', 'js/app.js', 'js/archive-export.js', 'js/preview-image-cache.js', 'js/batch-ad-builder.js', 'js/ad-restoration.js', 'js/ad-template-catalog.js', 'js/native-platform.js', 'js/native-app-init.js', 'css/native-app.css', 'css/tool.css']) {
  const bytes = await readFile(resolve(appRoot, asset));
  const version = 'sha256-' + createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const escapedAsset = asset.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const attribute = new RegExp('((?:src|href)="' + escapedAsset + '\\?v=)[^"]+');
  // Match only the version value. Attribute quoting and all other markup stay
  // owned by index.html rather than being regenerated by the package builder.
  versionedIndex = versionedIndex.replace(attribute, '$1' + version);
}
if (versionedIndex !== previousIndex) await writeFile(indexPath, versionedIndex, 'utf8');

// The game workbench uses the same packaging/cache helpers with relative URLs.
// Give its modified classic entry points the same content-derived cache policy.
const gameIndexPath = resolve(appRoot, 'game-builder/index.html');
const previousGameIndex = await readFile(gameIndexPath, 'utf8');
let gameIndex = previousGameIndex;
for (const asset of ['js/generator.js', 'js/app.js', 'js/legacy-template-source.js', 'js/game-template-versions.js', 'css/tool.css', '../js/archive-export.js', '../js/preview-image-cache.js', '../js/navbar-layout.js', '../js/ad-template-catalog.js', '../js/native-platform.js', '../js/native-app-init.js', '../css/native-app.css']) {
  const bytes = await readFile(resolve(appRoot, 'game-builder', asset));
  const version = 'sha256-' + createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const escapedAsset = asset.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  gameIndex = gameIndex.replace(new RegExp('((?:src|href)="' + escapedAsset + '\\?v=)[^"]+'), '$1' + version);
}
if (gameIndex !== previousGameIndex) await writeFile(gameIndexPath, gameIndex, 'utf8');
console.log('Template packages built: ' + packages.map(item => item.manifest.id).join(', '));
