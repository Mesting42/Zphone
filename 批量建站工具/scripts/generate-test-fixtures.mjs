import { mkdir, writeFile } from 'node:fs/promises';

const topics = ['tech', 'game', 'food', 'anime'];
function letters(number) {
  let value = number + 1; let result = '';
  while (value) { value -= 1; result = String.fromCharCode(97 + (value % 26)) + result; value = Math.floor(value / 26); }
  return result;
}
const articles = topics.map((topic, articleIndex) => {
  const prefix = ['cobalt', 'lantern', 'orchard', 'ribbon'][articleIndex];
  return {
    _development_notice: 'SYNTHETIC TEST FIXTURE — NOT FACTUAL CONTENT — NEVER USE FOR PUBLICATION OR ADSENSE REVIEW',
    title: `${prefix} ${topic} fixture`,
    content: Array.from({ length: 801 }, (_, index) => `${prefix}-${letters(index)}`).join(' '),
    image: `images/${prefix}.svg`, image_alt: `${prefix} synthetic test pattern`,
    excerpt: `Synthetic ${topic} article used only to test browser import and static page generation.`,
    category: topic, slug: `${prefix}-${topic}-fixture`, author: '', published_at: '', sources: [],
    fact_checked_by: '', fact_checked_at: '', cover_image_source: 'Synthetic asset generated by the local fixture script.'
  };
});
await mkdir(new URL('../examples/', import.meta.url), { recursive: true });
await writeFile(new URL('../examples/development-sample.json', import.meta.url), JSON.stringify({
  _notice: 'DEVELOPMENT TEST DATA ONLY. It intentionally lacks real operator, author, dates, and sources and must fail review gates.',
  articles
}, null, 2));
console.log(`Generated examples/development-sample.json with ${articles.length} intentionally non-publishable fixtures.`);
